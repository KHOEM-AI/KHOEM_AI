import fs from 'node:fs';
import crypto from 'node:crypto';
const r = JSON.parse(fs.readFileSync('corpus-sample/report.json', 'utf8'));
let fail = 0;
const ok = (n, c) => { console.log((c ? 'PASS ' : 'FAIL ') + n); if (!c) fail++; };
const src = id => (r.sources || []).find(s => s.dataset_id === id);
const blk = id => (r.blocked || []).find(b => b.dataset_id === id);
const sha = b => crypto.createHash('sha256').update(b).digest('hex');
const rawsha = f => sha(fs.readFileSync(f));
const norm = f => sha(fs.readFileSync(f, 'utf8').normalize('NFC').replace(/[\u200B\uFEFF]/g, ''));
const g = 'corpus-sample/raw/km-general.txt', x = 'corpus-sample/raw/km-exactdup.txt';
ok('fixture raw bytes differ', rawsha(g) !== rawsha(x));
ok('fixture normalized hash equal', norm(g) === norm(x));
ok('pipeline_version 0.2', r.pipeline_version === '0.2');
ok('eligibleWords equals sum of counted sources', r.eligibleWords === (r.sources || []).filter(s => s.counts_toward_target).reduce((a, s) => a + s.words, 0));
const a = src('sample-km-general-001');
ok('general: unique, 45 words', a && a.duplicate_exact === false && a.words === 45);
const d = src('sample-km-dup-001');
ok('dup-001: sentence-only dup', d && d.duplicate_exact === false && d.sentence_duplicates === 1 && d.kept === 0 && d.words === 0);
const e = blk('sample-km-exactdup-001');
ok('exactdup blocked as duplicate_exact', !!e && e.reasons.includes('duplicate_exact'));
const es = src('sample-km-exactdup-001');
ok('exactdup adds no words', !es || es.words === 0);
ok('sample words total 89', r.sources.filter(s => s.dataset_id.startsWith('sample-')).reduce((a, s) => a + s.words, 0) === 89);
ok('uniqueWords includes sample vocab (>=76)', r.uniqueWords >= 76);
ok('mot counted toward target (training approved)', (() => { const m = r.sources.find(s => s.dataset_id === 'mot-km-voa-001'); return !!m && m.counts_toward_target === true && !blk('mot-km-voa-001'); })());
ok('vocab blocked', !!blk('km-vocab-voa-001'));
ok('target 75M', r.target === 75000000);
ok('progressPercent matches eligibleWords/target', r.progressPercent === +(r.eligibleWords / r.target * 100).toFixed(6));
ok('only mot-km-voa-001 and km-wiki-001 count toward target', (r.sources || []).filter(s => s.counts_toward_target).map(s => s.dataset_id).sort().join() === 'km-wiki-001,mot-km-voa-001');
ok('every source reports non_khmer_skipped', (r.sources || []).every(s => typeof s.non_khmer_skipped === 'number'));
ok('mot-km-voa-001 skipped 821 non-Khmer articles', (() => { const m = src('mot-km-voa-001'); return !!m && m.non_khmer_skipped === 821; })());
process.exit(fail ? 1 : 0);
